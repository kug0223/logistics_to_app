/// [R7-P1-9] 알림센터가 보여 주는 기간 — ALfit 제품 정책.
///
/// ── 왜 기간을 두는가 ─────────────────────────────────────────────────────
///
/// 알림은 **최근 domain event로 들어가는 문**이지 장기 기록보관소가 아니다.
/// 지난 지원·계약·일정·근태·급여는 각자의 canonical 화면에 남아 있고,
/// 그쪽이 진짜 기록이다. 알림 목록이 무한히 길어지면 문으로서의 쓸모만
/// 떨어진다.
///
/// 이것을 업계 표준이라고 말하지 않는다. LinkedIn·Indeed·When I Work의
/// 공개 문서에서 알림 보존 기간 명세를 찾지 못했다. 이 90일은 ALfit이
/// 정한 값이고, 노쇼 집계 창(최근 90일)과 같은 길이라는 점만이 근거다.
///
/// ── 불변식 ──────────────────────────────────────────────────────────────
///
///   Notification age-out
///     != Notification delete
///     != Domain delete
///     != Task complete
///
/// 창 밖으로 나간 알림이 있었다고 해서 그 알림이 가리키던 일이 끝난 것은
/// 아니다. 서명 대기 계약은 여전히 계약 화면에, 검토 대기 지원서는 여전히
/// 지원 화면에 있다.
///
/// ── 물리 보존과의 관계 ──────────────────────────────────────────────────
///
/// 이 상수는 **화면이 보여 주는 기간**과 **오래된 알림 정리 job의 기준**
/// 둘 다에 쓰인다. 하나로 두는 이유가 있다.
///
/// 이 값을 도입하기 전, 정리 job은 이미 30일이었고 로그인할 때마다 돌고
/// 있었다. 거기에 90일 visible window를 얹으면 화면은 90일을 보여 준다고
/// 하지만 31일 전 알림은 애초에 존재하지 않는다 — 말과 사실이 어긋난다.
/// 둘이 갈라질 수 있는 구조를 남기지 않기 위해 상수 하나만 둔다.
///
/// 정리 job을 새로 만들지 않았다. 이미 있던 것의 기준을 선언한 정책에
/// 맞췄고, 방향은 **더 오래 보관하는 쪽**(30일 → 90일)이다.
class NotificationRetention {
  NotificationRetention._();

  /// 알림센터 visible history + 오래된 알림 정리 기준.
  static const int visibleDays = 90;

  /// 이 시각보다 오래된 알림은 목록에 넣지 않는다.
  ///
  /// [now]를 받는 이유는 경계를 테스트할 수 있어야 하기 때문이다.
  static DateTime cutoffFrom(DateTime now) =>
      now.subtract(const Duration(days: visibleDays));

  /// 이 알림이 visible window 안에 있는가.
  ///
  /// [createdAt]이 null이면 **보여 준다**. 시각을 모르는 것과 오래된 것은
  /// 다르고(UNKNOWN != OLD), 모른다는 이유로 숨기면 사용자는 그 알림이
  /// 있었다는 사실조차 알 수 없다. 반대로 오늘 것으로 취급해 맨 위에
  /// 올리지도 않는다 — 그 판단은 목록의 그룹핑이 따로 한다.
  ///
  /// 이런 legacy row는 정리 job도 지우지 않는다. `createdAt` 부등호 쿼리는
  /// 그 필드가 없는 문서를 애초에 반환하지 않기 때문이다. 즉 시각 없는
  /// 알림은 숨지도 지워지지도 않고 남는다 — 의도한 동작이다.
  static bool isVisible(DateTime? createdAt, DateTime now) {
    if (createdAt == null) return true;
    return !createdAt.isBefore(cutoffFrom(now));
  }
}
